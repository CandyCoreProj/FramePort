// (ไม่ใช้ RMDir /r ทั้งโฟลเดอร์ กันลบไฟล์ของผู้ใช้ถ้าติดตั้งลงโฟลเดอร์ที่มีไฟล์อื่นอยู่แล้ว)
const fs = require('node:fs');
const path = require('node:path');

exports.default = async function listInstalledFiles({ appOutDir, electronPlatformName }) {
  if (electronPlatformName !== 'win32') return;
  const lines = ['; generated by build/list-installed-files.js - do not edit'];
  for (const entry of fs.readdirSync(appOutDir, { withFileTypes: true })) {
    lines.push(entry.isDirectory()
      ? `RMDir /r "$INSTDIR\\${entry.name}"`
      : `Delete "$INSTDIR\\${entry.name}"`);
  }
  fs.writeFileSync(path.join(__dirname, 'uninstall-files.nsh'), lines.join('\r\n') + '\r\n');
};
